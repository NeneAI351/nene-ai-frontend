const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const paid=fs.readFileSync('paid-access.js','utf8');
const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
(async()=>{
  const dom=new JSDOM(html,{url:'https://neneai351.github.io/nene-ai-frontend/',runScripts:'outside-only'});
  const w=dom.window;
  w.localStorage.setItem('nene_ai_state_v1',JSON.stringify({credits:999999}));
  w.alert=()=>{};w.confirm=()=>false;w.fetch=async()=>({ok:false});
  const inline=[...w.document.querySelectorAll('script:not([src])')].map(tag=>tag.textContent).join('\n');
  w.eval(inline+'\nwindow.__getCredits=()=>credits;window.__editCredits=()=>{credits=999999;updateCredits();};');
  w.neneAuthGetAccessToken=async()=>null;
  w.NENE_DIRECTOR_CONFIG={backendUrl:'https://staging.example'};
  w.eval(paid);await tick();
  assert.equal(w.__getCredits(),0,'Local storage cannot grant welcome or purchased credits');
  assert.equal(w.document.getElementById('credits').textContent,'—');
  w.neneAuthGetAccessToken=async()=>'signed-in-token';
  const calls=[];
  w.fetch=async(url,options)=>{calls.push({url,options});return {ok:true,json:async()=>({paid_available_credits:'27.50',free_generation:false})};};
  await w.neneRefreshPaidWallet();
  assert.equal(w.document.getElementById('credits').textContent,'27.5');
  assert.equal(calls[0].options.headers.Authorization,'Bearer signed-in-token');
  assert.ok(calls[0].url.endsWith('/api/wallet/paid'));
  w.__editCredits();
  assert.equal(w.__getCredits(),27.5,'Local increments are not authoritative');
  assert.equal(JSON.parse(w.localStorage.getItem('nene_ai_state_v1')).credits,undefined);
  w.neneOpenPaidCredits();
  const policy=w.document.getElementById('paidRefundPolicy').textContent;
  assert.match(policy,/change-of-mind cash refunds are not offered/);
  assert.match(policy,/Applicable law/);
  assert.match(policy,/restores reserved credits/);
  // An in-flight response from a signed-out account cannot restore its balance.
  let finish;
  w.fetch=()=>new Promise(resolve=>finish=resolve);
  const pending=w.neneRefreshPaidWallet();await tick();
  w.neneAuthGetAccessToken=async()=>null;
  await w.neneRefreshPaidWallet();
  finish({ok:true,json:async()=>({paid_available_credits:'999',free_generation:false})});await pending;
  assert.equal(w.NENE_PAID_WALLET,null);
  assert.equal(w.document.getElementById('credits').textContent,'—');
  dom.window.close();
  console.log('Paid access UI verified: no local grants, authenticated paid balance, sign-out isolation and refund disclosure.');
})().catch(error=>{console.error(error);process.exit(1);});
